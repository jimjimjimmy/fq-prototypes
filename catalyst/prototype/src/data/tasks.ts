// Dynamic "today" — uses the real system clock mapped to 2026
// so the prototype always feels current regardless of when you run it.
const now = new Date();
export const today = new Date(2026, now.getMonth(), now.getDate());

const monthMap: Record<string, number> = {
  'Jan': 0, 'Feb': 1, 'Mar': 2, 'Apr': 3, 'May': 4, 'Jun': 5,
  'Jul': 6, 'Aug': 7, 'Sep': 8, 'Oct': 9, 'Nov': 10, 'Dec': 11,
};

// Parse "Feb 10" format dates into Date objects (year matches today)
export function parseTaskDate(dateStr: string): Date {
  const parts = dateStr.split(' ');
  const month = monthMap[parts[0]];
  const day = parseInt(parts[1], 10);
  return new Date(2026, month ?? 0, day);
}

// Helper to check if a task's due date is past due (before today)
export function isTaskOverdue(dueDate: string): boolean {
  const parts = dueDate.split(' ');
  if (parts.length !== 2) return false;
  const month = monthMap[parts[0]];
  const day = parseInt(parts[1], 10);
  if (month === undefined || isNaN(day)) return false;
  const dueDateObj = new Date(2026, month, day);
  return dueDateObj < today;
}

